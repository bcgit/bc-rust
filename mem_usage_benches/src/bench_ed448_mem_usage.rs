//! The purpose of this binary is to perform a single run of the primitive under test so that
//! its peak memory usage can be measured with:
//!
//! ```text
//! valgrind --tool=massif --heap=no --stacks=yes -- target/release/bench_ed448_mem_usage > /dev/null
//!
//! ms_print massif.out.*
//! ```
//!
//! Make sure you build in release mode!
//!
//! Note: print!() forces the compiler not to optimize away the actual code. The name of the bench
//! goes to stderr so that the junk on stdout can be piped to /dev/null.
//!
//! Main is at the bottom, controls which bench is actually run.
//!
//! The key, the message and the Ed448 signature are a published test vector (RFC 8032 Section
//! 7.4, "256 octets"), hard-coded so that no keygen or signing runs in a bench that does not
//! measure it. Every input reaches its operation through `black_box`, so the compiler cannot
//! shape the measured code to the constants: the message is longer than a SHAKE256 block, and
//! nothing lets a path that depends on a length or a value be dropped.

