/// Runs the operation under test in its own stack frame, with the key already loaded by the
/// caller.
///
/// `#[inline(never)]` matters here too: the bench functions inline the whole operation, so
/// without this boundary the operation's frame would be allocated on entry to the bench and the
/// key-load helper's frame would stack on top of it, reporting their sum instead of their max.
/// The closure returns nothing, so no result is copied back across the boundary.
#[inline(never)]
fn measure(f: impl FnOnce()) {
    f()
}

/// This exists so I can use /usr/bin/time to measure the base memory footprint of the harness.
fn bench_do_nothing() {
    eprintln!("DoNothing");

    print!("{}", 1 + 1);
}

/// This prints the in-memory size of the public and private key structs.
fn print_struct_sizes() {
    println!("Ed448PublicKey: {}", size_of::<Ed448PublicKey>());
    println!("Ed448PrivateKey: {}", size_of::<Ed448PrivateKey>());
}

/// Loads [`SK`]. `#[inline(never)]` so its decode temporaries are popped before the operation
/// runs.
#[inline(never)]
fn load_sk() -> Ed448PrivateKey {
    Ed448PrivateKey::from_bytes(black_box(&SK)).unwrap()
}

/// Loads [`PK`].
#[inline(never)]
fn load_pk() -> Ed448PublicKey {
    Ed448PublicKey::from_bytes(black_box(&PK)).unwrap()
}

/// Key generation: SHAKE256 and one fixed-base scalar multiplication. The RNG only copies its
/// seed out, so the figure is the key generation's own and not a DRBG's.
fn bench_ed448_keygen() {
    eprintln!("Ed448/KeyGen");

    measure(|| {
        let (pk, _sk) = keygen(&mut FixedSeedRNG::new(black_box(SK))).unwrap();
        print!("{:x?}", pk.encode());
    });
}

/// Key generation into a key the caller holds.
fn bench_ed448_keygen_out() {
    eprintln!("Ed448/KeyGenOut");

    let mut sk = Ed448PrivateKey::zeroized();
    measure(|| {
        let pk = keygen_out(&mut FixedSeedRNG::new(black_box(SK)), &mut sk).unwrap();
        print!("{:x?}", pk.encode());
    });
}

/// Decoding a private key, which derives its public key as key generation does.
fn bench_ed448_sk_from_bytes() {
    eprintln!("Ed448/PrivateKeyFromBytes");

    measure(|| {
        let sk = Ed448PrivateKey::from_bytes(black_box(&SK)).unwrap();
        black_box(&sk);
    });
}

/// Decoding a private key into a key the caller holds.
fn bench_ed448_sk_from_bytes_out() {
    eprintln!("Ed448/PrivateKeyFromBytesOut");

    let mut sk = Ed448PrivateKey::zeroized();
    measure(|| {
        Ed448PrivateKey::from_bytes_out(black_box(&SK), &mut sk).unwrap();
        black_box(&sk);
    });
}

/// Decoding a public key: decompression and the subgroup check, a variable-time multiplication
/// by the group order.
fn bench_ed448_pk_from_bytes() {
    eprintln!("Ed448/PublicKeyFromBytes");

    measure(|| {
        let pk = Ed448PublicKey::from_bytes(black_box(&PK)).unwrap();
        print!("{:x?}", pk.encode());
    });
}

/// The public key of a private key: a decompression of the stored encoding.
fn bench_ed448_pk() {
    eprintln!("Ed448/PublicKeyOfPrivateKey");

    let sk = load_sk();
    measure(|| {
        let pk = black_box(&sk).pk().unwrap();
        print!("{:x?}", pk.encode());
    });
}

/// Ed448 signing: two SHAKE256 passes and one fixed-base scalar multiplication.
fn bench_ed448_sign() {
    eprintln!("Ed448/Sign");

    let sk = load_sk();
    measure(|| {
        let sig = black_box(&sk).sign_deterministic(black_box(&MSG), black_box(None)).unwrap();
        print!("{:x?}", sig);
    });
}

/// Ed448 verification: one SHAKE256 pass and a variable-time double-scalar multiplication.
fn bench_ed448_verify() {
    eprintln!("Ed448/Verify");

    let pk = load_pk();
    measure(|| {
        black_box(&pk).verify(black_box(&MSG), black_box(None), black_box(&SIG)).unwrap();
        print!("ok");
    });
}

/// Ed448ph signing through the streaming signer, which the one-shot runs too.
fn bench_ed448ph_sign() {
    eprintln!("Ed448ph/Sign");

    let sk = load_sk();
    measure(|| {
        let mut signer =
            black_box(&sk).as_prehash().create_signer_deterministic(black_box(None)).unwrap();
        signer.do_update(black_box(&MSG));
        let sig = signer.do_final().unwrap();
        print!("{:x?}", sig);
    });
}

/// Ed448ph verification through the streaming verifier.
fn bench_ed448ph_verify() {
    eprintln!("Ed448ph/Verify");

    let pk = load_pk();
    measure(|| {
        let mut verifier = black_box(&pk).as_prehash().create_verifier(black_box(None)).unwrap();
        verifier.do_update(black_box(&MSG));
        verifier.do_verify_final(black_box(&SIG_PH)).unwrap();
        print!("ok");
    });
}

