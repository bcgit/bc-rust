//! The precomputed multiples of the Ed25519 base point B: constants, so that neither signing
//! nor verification needs an allocation or a first-use initialisation.
//!
//! The field type has a destructor, which rules out computing these in a `const` on stable
//! Rust, so the limbs are written out. They are generated: the unit test
//! `point::tests::print_base_point_tables` rebuilds the tables from B at run time and prints
//! everything below the `entry` function, and `the_base_point_tables_are_what_b_generates`
//! compares that rebuild with what is here on every test run. To regenerate:
//!
//! ```text
//! cargo test -p bouncycastle-ec --lib ed25519::point::tests::print_base_point_tables -- --ignored --nocapture
//! ```
//!
//! Every field element is in canonical limbs, least significant first.

