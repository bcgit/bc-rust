//! DHKEM over P-256, P-384 and P-521 (RFC 9180 Section 4.1), on the ECC CDH keys.
//!
//! [`ECCDHPublicKey`] and [`ECCDHPrivateKey`] over [`P256`], [`P384`] and [`P521`] carry the KEM
//! roles, [`EncapsulatingKey`] and [`DecapsulatingKey`], with `()` as the parameters. The KEM
//! itself is `crate::dhkem`'s generic [`DHKEM`], over [`ECCDH`] as its group.
//!
//! | KEM                        | `kem_id` | Nsecret | Nenc, Npk | Nsk | Marker                     |
//! |----------------------------|----------|---------|-----------|-----|----------------------------|
//! | DHKEM(P-256, HKDF-SHA256)  | 0x0010   | 32      | 65        | 32  | [`DHKEM_P256_HKDF_SHA256`] |
//! | DHKEM(P-384, HKDF-SHA384)  | 0x0011   | 48      | 97        | 48  | [`DHKEM_P384_HKDF_SHA384`] |
//! | DHKEM(P-521, HKDF-SHA512)  | 0x0012   | 64      | 133       | 66  | [`DHKEM_P521_HKDF_SHA512`] |
//!
//! (RFC 9180 Section 7.1, Table 2.) The other curves of this module have no DHKEM in RFC 9180.
//!
//! ```
//! use bouncycastle_core::kem_key::{DecapsulatingKey, EncapsulatingKey};
//! use bouncycastle_ec::P256;
//! use bouncycastle_ec::eccdh::keys::keygen;
//! use bouncycastle_rng::HashDRBG_SHA512;
//!
//! let mut rng = HashDRBG_SHA512::new_from_os();
//! let (pk, sk) = keygen::<P256>(&mut rng).unwrap();
//!
//! // The sender encapsulates against the recipient's public key...
//! let (ss, ct) = pk.encaps(&mut rng, ())?;
//!
//! // ...and the recipient recovers the same shared secret from the ciphertext.
//! assert_eq!(sk.decaps(&ct, ())?, ss);
//! # Ok::<(), bouncycastle_core::errors::KEMError>(())
//! ```
//!
//! # 🚨 Security Considerations 🚨
//!
//! * The shared secret depends on the recipient's long-term key alone: there is no forward
//!   secrecy with respect to it (RFC 9180 Section 9.1).
//! * A key agreement key should serve one purpose. A key used here as a DHKEM key should not
//!   also be used for raw ECC CDH (SP 800-56A Rev. 3 Section 5.6.3.2).
//! * The ephemeral key of an encapsulation is generated by [`keygen`], which builds it in a frame
//!   of its own and overwrites the stack it used afterwards. The Diffie-Hellman products,
//!   `pk(skR)`, `DeriveKeyPair` and the KEM's HKDF steps run the same way, so no private key, DH
//!   output or PRK is left on the dead stack (`dev_scripts/check_ecdsa_stack.sh`).

