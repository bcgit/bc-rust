/// `DeriveKeyPair(ikm)` (RFC 9180 Section 7.1.3) for the curve `C`: the key pair that the
/// rejection sampling over `ikm` gives. `ikm` must be a seed or a full-entropy key, at the
/// curve's strength or more.
///
/// # Errors
/// [`KEMError::KeyGenError`] if `ikm` does not meet those requirements, or if 256 candidates are
/// all refused, a likelihood the RFC calls "negligibly small".
pub fn derive_key_pair<C: DhkemCurve>(
    ikm: &impl KeyMaterialTrait,
) -> Result<(ECCDHPublicKey<C>, ECCDHPrivateKey<C>), KEMError> {
    C::derive_key_pair(ikm)
}

/// The curve as the Diffie-Hellman group of a DHKEM (RFC 9180 Sections 4.1 and 7.1).
impl<C, const N_PK: usize, const N_SK: usize, const N_DH: usize> DHKEMParams<N_PK, N_SK, N_DH>
    for ECCDH<C>
where
    C: DhkemCurve
        + Curve<PkUncompressed = [u8; N_PK], ScalarBytes = [u8; N_SK], FeBytes = [u8; N_DH]>,
{
    type PublicKey = ECCDHPublicKey<C>;
    type PrivateKey = ECCDHPrivateKey<C>;
    type KDFHash = C::KDFHash;
    const KEM_ID: u16 = C::KEM_ID;
    const DERIVE_KEY_PAIR: DeriveKeyPairForm = DeriveKeyPairForm::Candidate { bitmask: C::BITMASK };

    fn with_generated_key_pair<R>(
        rng: &mut dyn RNG,
        f: impl FnOnce(&ECCDHPublicKey<C>, &ECCDHPrivateKey<C>) -> R,
    ) -> Result<R, KEMError> {
        // The pair is used where keygen returned it, and dropped there: moving the key out of
        // the `Result` would leave a copy of it that nothing wipes.
        let generated = keygen::<C>(rng);
        if let Ok((pk, sk)) = &generated {
            return Ok(f(pk, sk));
        }
        // keygen fails only through the RNG.
        match generated {
            Err(KeyAgreementError::RNGError(e)) => Err(KEMError::RNGError(e)),
            _ => Err(KEMError::GenericError("ECC key generation failed")),
        }
    }

    /// Section 7.1.3's `sk = OS2IP(bytes)` and its test `sk == 0 or sk >= order`: `None` unless
    /// the value is in `[1, n-1]`.
    // The key is built in a wiped frame, as the private key's `from_bytes` builds it.
    fn private_key_from_bytes(sk: &[u8; N_SK]) -> Option<ECCDHPrivateKey<C>> {
        in_wiped_frame::<C::Limbs, DECODE_STACK_PER_LIMB, DECODE_STACK_FIXED, _>(|| {
            private_key_from_be_bytes::<C, _>(
                sk,
                |d| Some(ECCDHPrivateKey::from_scalar(d.clone())),
                || None,
            )
        })
    }

    fn pk(sk: &ECCDHPrivateKey<C>) -> ECCDHPublicKey<C> {
        let (x, y) = public_point_wiped::<C>(sk.scalar());
        ECCDHPublicKey { x, y }
    }

    /// Section 4.1: the DH output is "the x-coordinate of the resulting elliptic curve point",
    /// and Section 7.1.4: "senders and recipients MUST ensure the Diffie-Hellman shared secret
    /// is not the point at infinity". The peer's key passed the public-key validation of
    /// Section 7.1.4 when it was decoded.
    fn dh_into(
        sk: &ECCDHPrivateKey<C>,
        pk: &ECCDHPublicKey<C>,
        out: &mut Secret<[u8; N_DH]>,
    ) -> Result<(), KeyAgreementError> {
        // In a wiped frame, as ECC CDH's agreement runs: the product's intermediates depend on
        // the private key and on the DH output.
        in_wiped_frame::<C::Limbs, AGREE_STACK_PER_LIMB, AGREE_STACK_FIXED, _>(|| {
            let q = C::Point::from_affine(pk.x, pk.y);
            let mut p = C::multiply_point(sk.scalar(), &q);
            z_bytes_from_product::<C, N_DH>(&mut p, out)
        })
    }

    /// Section 7.1.1: "the uncompressed Elliptic-Curve-Point-to-Octet-String conversion".
    fn serialize_public_key(pk: &ECCDHPublicKey<C>) -> [u8; N_PK] {
        C::encode_uncompressed(&pk.x, &pk.y)
    }

    /// Section 7.1.1: "the uncompressed Octet-String-to-Elliptic-Curve-Point conversion", with
    /// the validation of Section 7.1.4 (coordinates in range, on the curve, not the point at
    /// infinity), which the curve's decoder performs. Only the uncompressed form is accepted.
    fn deserialize_public_key(pkm: &[u8; N_PK]) -> Result<ECCDHPublicKey<C>, KEMError> {
        // SEC 1 Section 2.3.3: an uncompressed point starts with the octet 04.
        if pkm[0] != 0x04 {
            return Err(KEMError::DecodingError("a DHKEM public key is an uncompressed point"));
        }
        let (x, y) = C::decode(pkm)
            .ok_or(KEMError::DecodingError("invalid or out-of-range point for the curve"))?;
        Ok(ECCDHPublicKey { x, y })
    }
}

/// DHKEM over the curve `C` with the KDF RFC 9180 pairs it with (Section 7.1, Table 2): the
/// algorithm of the KEM roles on the ECC CDH keys, as distinct from the agreement [`ECCDH`].
pub struct ECDHKEM<C: DhkemCurve>(PhantomData<C>);

impl<C: DhkemCurve> Algorithm for ECDHKEM<C> {
    const ALG_NAME: &'static str = C::KEM_NAME;
    const MAX_SECURITY_STRENGTH: SecurityStrength = C::STRENGTH;
}

impl<C: DhkemCurve> KEMAlgorithm for ECDHKEM<C> {}

impl<C: DhkemCurve> HpkeKem for ECDHKEM<C> {
    const KEM_ID: u16 = C::KEM_ID;
}

/// DHKEM(P-256, HKDF-SHA256), `kem_id` 0x0010.
#[allow(non_camel_case_types)]
pub type DHKEM_P256_HKDF_SHA256 = ECDHKEM<P256>;
/// DHKEM(P-384, HKDF-SHA384), `kem_id` 0x0011.
#[allow(non_camel_case_types)]
pub type DHKEM_P384_HKDF_SHA384 = ECDHKEM<P384>;
/// DHKEM(P-521, HKDF-SHA512), `kem_id` 0x0012.
#[allow(non_camel_case_types)]
pub type DHKEM_P521_HKDF_SHA512 = ECDHKEM<P521>;

/// The encapsulator an [`ECCDHPublicKey`] hands out through [`EncapsulatingKey`]: `Encap` of
/// RFC 9180 Section 4.1, the ciphertext being the ephemeral public key `enc`. It borrows the
/// recipient's key.
pub struct ECDHKEMEncapsulator<'k, C: DhkemCurve> {
    pk: &'k ECCDHPublicKey<C>,
}

impl<C: DhkemCurve> Algorithm for ECDHKEMEncapsulator<'_, C> {
    const ALG_NAME: &'static str = ECDHKEM::<C>::ALG_NAME;
    const MAX_SECURITY_STRENGTH: SecurityStrength = ECDHKEM::<C>::MAX_SECURITY_STRENGTH;
}

impl<C, const N_ENC: usize, const N_SECRET: usize> KEMEncapsulator<N_ENC, N_SECRET>
    for ECDHKEMEncapsulator<'_, C>
where
    C: DhkemCurve<SharedSecret = KeyMaterial<N_SECRET>> + Curve<PkUncompressed = [u8; N_ENC]>,
{
    /// `Encap(pkR)`, drawing the ephemeral key pair from `rng`.
    ///
    /// # Errors
    /// [`KEMError::RNGError`] if `rng` is weaker than the curve or fails to deliver.
    fn encaps_out(
        &self,
        rng: &mut dyn RNG,
        ct: &mut [u8; N_ENC],
        ss: &mut KeyMaterial<N_SECRET>,
    ) -> Result<usize, KEMError> {
        ct.fill(0);
        ss.zeroize();
        C::encap_out(self.pk, rng, ct, ss)
    }
}

/// The ECC CDH public keys of the three curves encapsulate as that curve's DHKEM, with `()` as
/// the parameters.
impl<C, const N_ENC: usize, const N_SECRET: usize> EncapsulatingKey<(), N_ENC, N_SECRET>
    for ECCDHPublicKey<C>
where
    C: DhkemCurve<SharedSecret = KeyMaterial<N_SECRET>> + Curve<PkUncompressed = [u8; N_ENC]>,
{
    type Algorithm = ECDHKEM<C>;
    type Encapsulator<'k> = ECDHKEMEncapsulator<'k, C>;

    fn create_encapsulator<'k>(
        &'k self,
        _params: (),
    ) -> Result<ECDHKEMEncapsulator<'k, C>, KEMError> {
        Ok(ECDHKEMEncapsulator { pk: self })
    }
}

/// The decapsulator an [`ECCDHPrivateKey`] hands out through [`DecapsulatingKey`]: `Decap` of
/// RFC 9180 Section 4.1. It borrows the recipient's key.
pub struct ECDHKEMDecapsulator<'k, C: DhkemCurve> {
    sk: &'k ECCDHPrivateKey<C>,
    /// `pk(skR)`, which `Decap` binds into the secret: computed once, when the worker is made.
    pk: ECCDHPublicKey<C>,
}

impl<C: DhkemCurve> Algorithm for ECDHKEMDecapsulator<'_, C> {
    const ALG_NAME: &'static str = ECDHKEM::<C>::ALG_NAME;
    const MAX_SECURITY_STRENGTH: SecurityStrength = ECDHKEM::<C>::MAX_SECURITY_STRENGTH;
}

impl<C, const N_ENC: usize, const N_SECRET: usize> KEMDecapsulator<N_ENC, N_SECRET>
    for ECDHKEMDecapsulator<'_, C>
where
    C: DhkemCurve<SharedSecret = KeyMaterial<N_SECRET>> + Curve<PkUncompressed = [u8; N_ENC]>,
{
    /// `Decap(enc, skR)`, with the ciphertext `ct` as `enc`.
    ///
    /// # Errors
    /// [`KEMError::DecapsulationFailed`] if `ct` is not an uncompressed point on the curve.
    fn decaps_out(
        &self,
        ct: &[u8; N_ENC],
        ss: &mut KeyMaterial<N_SECRET>,
    ) -> Result<usize, KEMError> {
        ss.zeroize();
        C::decap_out(ct, self.sk, &self.pk, ss)
    }
}

/// The ECC CDH private keys of the three curves decapsulate as that curve's DHKEM, with `()` as
/// the parameters.
impl<C, const N_ENC: usize, const N_SECRET: usize> DecapsulatingKey<(), N_ENC, N_SECRET>
    for ECCDHPrivateKey<C>
where
    C: DhkemCurve<SharedSecret = KeyMaterial<N_SECRET>> + Curve<PkUncompressed = [u8; N_ENC]>,
{
    type Algorithm = ECDHKEM<C>;
    type Decapsulator<'k> = ECDHKEMDecapsulator<'k, C>;

    fn create_decapsulator<'k>(
        &'k self,
        _params: (),
    ) -> Result<ECDHKEMDecapsulator<'k, C>, KEMError> {
        let (x, y) = public_point_wiped::<C>(self.scalar());
        Ok(ECDHKEMDecapsulator { sk: self, pk: ECCDHPublicKey { x, y } })
    }
}

/// `AuthEncap(pkR, skS)` of the curve's DHKEM (RFC 9180 Section 4.1), on the recipient's public
/// key: what HPKE's Auth and AuthPSK modes run over.
impl<C, const N_ENC: usize, const N_SECRET: usize> AuthEncapsulatingKey<N_ENC, N_SECRET>
    for ECCDHPublicKey<C>
where
    C: DhkemCurve<SharedSecret = KeyMaterial<N_SECRET>> + Curve<PkUncompressed = [u8; N_ENC]>,
{
    type SenderPrivateKey = ECCDHPrivateKey<C>;

    /// # Errors
    /// [`KEMError::RNGError`] if `rng` is weaker than the curve or fails to deliver.
    fn auth_encaps_out(
        &self,
        rng: &mut dyn RNG,
        sk_s: &ECCDHPrivateKey<C>,
        enc: &mut [u8; N_ENC],
        ss: &mut KeyMaterial<N_SECRET>,
    ) -> Result<usize, KEMError> {
        enc.fill(0);
        ss.zeroize();
        C::auth_encap_out(self, sk_s, rng, enc, ss)
    }
}

/// `AuthDecap(enc, skR, pkS)` of the curve's DHKEM (RFC 9180 Section 4.1), on the recipient's
/// private key.
impl<C, const N_ENC: usize, const N_SECRET: usize> AuthDecapsulatingKey<N_ENC, N_SECRET>
    for ECCDHPrivateKey<C>
where
    C: DhkemCurve<SharedSecret = KeyMaterial<N_SECRET>> + Curve<PkUncompressed = [u8; N_ENC]>,
{
    type SenderPublicKey = ECCDHPublicKey<C>;

    /// # Errors
    /// [`KEMError::DecapsulationFailed`] if `enc` is not an uncompressed point on the curve.
    fn auth_decaps_out(
        &self,
        enc: &[u8; N_ENC],
        pk_s: &ECCDHPublicKey<C>,
        ss: &mut KeyMaterial<N_SECRET>,
    ) -> Result<usize, KEMError> {
        ss.zeroize();
        // pk(skR), which AuthDecap binds into the secret.
        let (x, y) = public_point_wiped::<C>(self.scalar());
        C::auth_decap_out(enc, self, &ECCDHPublicKey { x, y }, pk_s, ss)
    }
}
