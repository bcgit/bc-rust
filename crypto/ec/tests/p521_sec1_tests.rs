fn fe(limbs: [u64; 9]) -> P521FieldElement {
    P521FieldElement::from_limbs(limbs)
}

#[test]
fn known_answer_encode_uncompressed() {
    assert_eq!(encode_uncompressed(&fe(G_X), &fe(G_Y)), UNCOMPRESSED_G);
}

#[test]
fn known_answer_encode_compressed() {
    assert_eq!(encode_compressed(&fe(G_X), &fe(G_Y)), COMPRESSED_G, "G has even y -> tag 0x02");
    assert_eq!(
        encode_compressed(&fe(THREE_G_X), &fe(THREE_G_Y)),
        COMPRESSED_3G,
        "3G has odd y -> tag 0x03"
    );
}

#[test]
fn known_answer_decode_uncompressed() {
    let (x, y) = decode(&UNCOMPRESSED_G).expect("valid uncompressed point");
    assert_eq!(x, fe(G_X));
    assert_eq!(y, fe(G_Y));
}

#[test]
fn known_answer_decode_compressed() {
    let (x, y) = decode(&COMPRESSED_G).expect("valid compressed point, tag 0x02");
    assert_eq!(x, fe(G_X));
    assert_eq!(y, fe(G_Y));

    let (x3, y3) = decode(&COMPRESSED_3G).expect("valid compressed point, tag 0x03");
    assert_eq!(x3, fe(THREE_G_X));
    assert_eq!(y3, fe(THREE_G_Y));
}

#[test]
fn round_trip_uncompressed_and_compressed() {
    for (x, y) in [(G_X, G_Y), (THREE_G_X, THREE_G_Y)] {
        let uncompressed = encode_uncompressed(&fe(x), &fe(y));
        assert_eq!(decode(&uncompressed), Some((fe(x), fe(y))));

        let compressed = encode_compressed(&fe(x), &fe(y));
        assert_eq!(decode(&compressed), Some((fe(x), fe(y))));

        assert!(decode_point(&uncompressed).unwrap().to_affine().is_some());
    }
}

#[test]
fn decode_rejects_malformed_input() {
    assert_eq!(decode(&[]), None);
    assert_eq!(decode(&[0x04; 132]), None);
    assert_eq!(decode(&[0x04; 134]), None);
    assert_eq!(decode(&[0x02; 32]), None);

    let mut bad_tag_133 = UNCOMPRESSED_G;
    bad_tag_133[0] = 0x02;
    assert_eq!(decode(&bad_tag_133), None);

    let mut bad_tag_67 = COMPRESSED_G;
    bad_tag_67[0] = 0x04;
    assert_eq!(decode(&bad_tag_67), None);

    assert_eq!(decode(&[0x00]), None);

    let mut x_too_big = COMPRESSED_G;
    x_too_big[1..67].fill(0xff);
    assert_eq!(decode(&x_too_big), None);

    let mut no_root = COMPRESSED_G;
    no_root[1..67].fill(0);
    no_root[66] = 3; // x = 3, confirmed (in the Python derivation) to have no square root
    assert_eq!(decode(&no_root), None);

    let mut not_on_curve = UNCOMPRESSED_G;
    not_on_curve[132] ^= 0x01;
    assert_eq!(decode(&not_on_curve), None);

    let mut y_too_big = UNCOMPRESSED_G;
    y_too_big[67..133].fill(0xff);
    assert_eq!(decode(&y_too_big), None);
}
