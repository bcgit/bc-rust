/// Length in bytes of the serialized state of [`Ascon_AEAD128`].
/// Layout: 3-byte library version || 1-byte state tag || 40-byte permutation state (5 × u64 LE)
/// || 1-byte byte position within the current rate block || 1-byte phase || 16-byte held-back
/// tail || 1-byte tail length.
/// The secret key is **not** serialized; it is re-supplied to [`SuspendableKeyed::from_suspended`].
/// The direction is not serialized either: it is the type the state is resumed into.
pub const SUSPENDED_ASCON_AEAD128_STATE_LEN: usize = 63;

const AEAD128_STATE_TAG: u8 = 0x04;

// Offsets within the state, after the 3-byte version prefix.
const STATE_OFFSET: usize = 1;
const POS_OFFSET: usize = STATE_OFFSET + 40;
const PHASE_OFFSET: usize = POS_OFFSET + 1;
const TAIL_OFFSET: usize = PHASE_OFFSET + 1;
const TAIL_LEN_OFFSET: usize = TAIL_OFFSET + TAG_LEN;
const _: () = assert!(TAIL_LEN_OFFSET + 1 == SUSPENDED_ASCON_AEAD128_STATE_LEN - 3);

impl<Dir> SuspendableKeyed<SUSPENDED_ASCON_AEAD128_STATE_LEN> for Ascon_AEAD128<Dir> {
    // The 128-bit key must be re-supplied when resuming; it is never part of the serialized state,
    // and is re-validated exactly as the constructors validate it.
    type Key = KeyMaterial<KEY_LEN>;

    fn suspend(self) -> [u8; SUSPENDED_ASCON_AEAD128_STATE_LEN] {
        let mut out_to_return = [0u8; SUSPENDED_ASCON_AEAD128_STATE_LEN];
        // infallible: add_lib_ver returns a slice of exactly SUSPENDED_ASCON_AEAD128_STATE_LEN - 3 = 60 bytes.
        let out: &mut [u8; SUSPENDED_ASCON_AEAD128_STATE_LEN - 3] =
            add_lib_ver(&mut out_to_return).try_into().unwrap();

        out[0] = AEAD128_STATE_TAG;
        for i in 0..5 {
            out[STATE_OFFSET + i * 8..STATE_OFFSET + i * 8 + 8]
                .copy_from_slice(&self.state[i].to_le_bytes());
        }
        debug_assert!(self.pos < RATE);
        out[POS_OFFSET] = self.pos as u8;
        out[PHASE_OFFSET] = self.phase as u8;
        out[TAIL_OFFSET..TAIL_LEN_OFFSET].copy_from_slice(&self.tail);
        debug_assert!(self.tail_len <= TAG_LEN);
        out[TAIL_LEN_OFFSET] = self.tail_len as u8;

        out_to_return
    }

    fn from_suspended(
        serialized_state: [u8; SUSPENDED_ASCON_AEAD128_STATE_LEN],
        key: &Self::Key,
    ) -> Result<Self, SuspendableError> {
        // infallible: check_lib_ver returns a slice of exactly SUSPENDED_ASCON_AEAD128_STATE_LEN - 3 = 60 bytes.
        let input: &[u8; SUSPENDED_ASCON_AEAD128_STATE_LEN - 3] =
            check_lib_ver(&serialized_state, None)?.try_into().unwrap();

        if input[0] != AEAD128_STATE_TAG {
            return Err(SuspendableError::InvalidData);
        }
        let mut state = Secret::<AsconState>::new();
        for i in 0..5 {
            // infallible: each slice is exactly 8 bytes by construction.
            state[i] = u64::from_le_bytes(
                input[STATE_OFFSET + i * 8..STATE_OFFSET + i * 8 + 8].try_into().unwrap(),
            );
        }
        let pos = input[POS_OFFSET] as usize;
        if pos >= RATE {
            return Err(SuspendableError::InvalidData);
        }
        let phase = Phase::from_u8(input[PHASE_OFFSET])?;
        // A nonzero byte position means at least one AAD/data byte has been absorbed into the
        // current rate block, which is impossible while still in `Init`.
        if pos != 0 && phase == Phase::Init {
            return Err(SuspendableError::InvalidData);
        }
        let mut tail = [0u8; TAG_LEN];
        tail.copy_from_slice(&input[TAIL_OFFSET..TAIL_LEN_OFFSET]);
        let tail_len = input[TAIL_LEN_OFFSET] as usize;
        // The tail is only ever filled by `do_decrypt_out`, which moves the phase to `Data` on
        // its first call, so a held-back tail in any other phase is inconsistent.
        if tail_len > TAG_LEN || (tail_len != 0 && phase != Phase::Data) {
            return Err(SuspendableError::InvalidData);
        }

        let key_words = Self::checked_key(key).map_err(|_| SuspendableError::InvalidData)?;
        let mut key_secret = Secret::<[u64; 2]>::new();
        *key_secret = key_words;

        Ok(Self { key: key_secret, state, pos, phase, tail, tail_len, _dir: PhantomData })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // Phase is private, so its `as u8` / from_u8 round trip -- exercised end-to-end via
    // suspend/resume in tests/aead128_tests.rs for the states reachable there -- is pinned
    // directly here for every discriminant, including the two a successful resume never needs to
    // decode into (Init and Aad never survive to be the end state of a still-running cipher in
    // the integration tests, since further processing always advances them to Data).
    #[test]
    fn phase_u8_round_trip() {
        for p in [Phase::Init, Phase::Aad, Phase::Data] {
            assert_eq!(Phase::from_u8(p as u8).unwrap(), p, "round trip failed for {p:?}");
        }
        for v in [3u8, 200] {
            assert!(Phase::from_u8(v).is_err(), "discriminant {v} must be rejected");
        }
    }
}
