#[test]
fn decode_rejects_non_canonical_leading_zero_pad() {
    // r's INTEGER content is `00 07`: its high bit is not set (0x07), so the 0x00 pad byte in
    // front of it is redundant -- ITU-T X.690 §8.3.2 forbids exactly this.
    let malformed: [u8; 9] = [0x30, 0x07, 0x02, 0x02, 0x00, 0x07, 0x02, 0x01, 0x09];
    let mut r_out = [0u8; 1];
    let mut s_out = [0u8; 1];
    assert!(decode(&malformed, &mut r_out, &mut s_out).is_none());
}

#[test]
fn decode_rejects_negative_integer() {
    // A lone 0x80 content byte has its high bit set with no 0x00 pad -- a negative two's-complement
    // value, which r/s can never legitimately be.
    let malformed: [u8; 7] = [0x30, 0x05, 0x02, 0x01, 0x80, 0x02, 0x00];
    let mut r_out = [0u8; 1];
    let mut s_out = [0u8; 1];
    // second INTEGER's content_len 0 also invalid (empty content), but the negative check on the
    // first INTEGER must reject before that's even reached.
    assert!(decode(&malformed, &mut r_out, &mut s_out).is_none());
}

#[test]
fn decode_rejects_indefinite_length() {
    // 0x80 as the outer SEQUENCE's length octet is BER's indefinite-length form (X.690 §8.1.3.6),
    // not a definite length; DER (§10.1) requires the definite form.
    let der: [u8; 9] = [0x30, 0x80, 0x02, 0x01, 0x07, 0x02, 0x01, 0x09, 0x00];
    let mut r_out = [0u8; 1];
    let mut s_out = [0u8; 1];
    assert!(decode(&der, &mut r_out, &mut s_out).is_none());
}

