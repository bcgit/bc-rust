/// xorshift64* PRNG, fixed seed: same rationale as the `ec` crate's field-arithmetic property tests.
struct Xorshift64(u64);

impl Xorshift64 {
    fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }

    fn next_bytes(&mut self, n: usize) -> Vec<u8> {
        let mut out = Vec::with_capacity(n);
        while out.len() < n {
            out.extend_from_slice(&self.next_u64().to_le_bytes());
        }
        out.truncate(n);
        out
    }
}

#[test]
fn round_trips_over_many_pseudorandom_widths_and_values() {
    let mut rng = Xorshift64(0xD1CE5EED_D1CE5EEDu64);
    for &n in &[32usize, 48, 66] {
        for _ in 0..200 {
            let r = rng.next_bytes(n);
            let s = rng.next_bytes(n);
            let mut out = vec![0u8; max_len(n)];
            let len = encode(&r, &s, &mut out);
            assert!(len <= max_len(n));

            let mut r_out = vec![0u8; n];
            let mut s_out = vec![0u8; n];
            decode(&out[..len], &mut r_out, &mut s_out).expect("round trip must decode");
            assert_eq!(r_out, r);
            assert_eq!(s_out, s);

            // Any single flipped bit in a well-formed encoding must not silently decode to a
            // *different* valid-looking (r, s) pair with a truncated read -- either it's rejected,
            // or (rarely, e.g. a bit flip inside an unused zero-padding position that DER forbids
            // anyway) it still equals the original; check it's never a mismatched success.
            for bit_pos in [0usize, len.saturating_sub(1)] {
                let mut flipped = out[..len].to_vec();
                flipped[bit_pos] ^= 0xFF;
                let mut fr = vec![0u8; n];
                let mut fs = vec![0u8; n];
                if decode(&flipped, &mut fr, &mut fs).is_some() {
                    assert!(
                        fr != r || fs != s,
                        "corrupting byte {bit_pos} must not be silently ok"
                    );
                }
            }
        }
    }
}

#[test]
fn decode_rejects_empty_integer_content() {
    // X.690 §8.3.1: an INTEGER's content is one or more octets, so `02 00` is malformed on its own
    // (unlike `decode_rejects_negative_integer`, where the empty second INTEGER sits behind a
    // negative first one that is rejected before it is ever reached). The second INTEGER is
    // well-formed, so the empty first one is the only thing that can be rejecting this.
    let malformed: [u8; 7] = [0x30, 0x05, 0x02, 0x00, 0x02, 0x01, 0x09];
    let mut r_out = [0u8; 1];
    let mut s_out = [0u8; 1];
    assert!(decode(&malformed, &mut r_out, &mut s_out).is_none());
}

#[test]
fn decode_rejects_sequence_content_not_exactly_filled_by_the_two_integers() {
    // The SEQUENCE's declared length matches the buffer (so this is neither truncation nor
    // trailing bytes after the SEQUENCE), and both INTEGERs are well-formed, but two more bytes
    // sit inside the SEQUENCE after them: `Ecdsa-Sig-Value` has exactly two components.
    let malformed: [u8; 10] = [0x30, 0x08, 0x02, 0x01, 0x07, 0x02, 0x01, 0x09, 0x05, 0x00];
    let mut r_out = [0u8; 1];
    let mut s_out = [0u8; 1];
    assert!(decode(&malformed, &mut r_out, &mut s_out).is_none());
}
