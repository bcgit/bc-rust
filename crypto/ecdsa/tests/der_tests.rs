#[test]
fn max_len_boundary_at_the_short_to_long_form_transition() {
    // content_len = 2*(n+3); n=60 -> 126 (< 0x80, short-form header), n=61 -> 128 (>= 0x80,
    // long-form header). None of this crate's actual curve widths (32/48/66) land near this
    // boundary, so it needs a dedicated, curve-independent check.
    assert_eq!(max_len(60), 2 + 126);
    assert_eq!(max_len(61), 3 + 128);
}

#[test]
fn round_trip_at_the_sequence_content_length_128_boundary() {
    // r, s both 61 bytes with the high bit set (forcing a pad byte each): every INTEGER TLV is
    // 2 + 61 + 1 = 64 bytes, so the SEQUENCE content is exactly 128 bytes -- the smallest width at
    // which the SEQUENCE's own length must use the long form (0x81 0x80), per max_len's docs.
    let r = [0xffu8; 61];
    let s = [0xffu8; 61];
    let mut out = vec![0u8; max_len(61)];
    let len = encode(&r, &s, &mut out);
    assert_eq!(len, 131);
    assert_eq!(
        &out[..3],
        &[0x30, 0x81, 0x80],
        "SEQUENCE length must use the long form at exactly 128"
    );

    let mut r_out = vec![0u8; 61];
    let mut s_out = vec![0u8; 61];
    decode(&out[..len], &mut r_out, &mut s_out)
        .expect("must accept a minimal long-form length of exactly 128");
    assert_eq!(r_out, r);
    assert_eq!(s_out, s);
}

#[test]
fn decode_rejects_indefinite_length_even_when_the_rest_looks_like_a_valid_128_byte_body() {
    // Builds on the same 61-byte encoding as the test above: its SEQUENCE content is genuinely 128
    // valid bytes, so a decoder that mistreated the outer length octet 0x80 as "short form, value
    // 128" (instead of the indefinite-length marker DER forbids) would find a declared length that
    // matches the buffer and content that parses as two valid INTEGERs -- and wrongly accept it.
    // This is what makes the test discriminate the bug from a coincidental reject, unlike a buffer
    // where the trailing content doesn't line up.
    let r = [0xffu8; 61];
    let s = [0xffu8; 61];
    let mut out = vec![0u8; max_len(61)];
    let len = encode(&r, &s, &mut out);
    assert_eq!(&out[..3], &[0x30, 0x81, 0x80]);

    let mut malformed = vec![0x30, 0x80];
    malformed.extend_from_slice(&out[3..len]);

    let mut r_out = vec![0u8; 61];
    let mut s_out = vec![0u8; 61];
    assert!(decode(&malformed, &mut r_out, &mut s_out).is_none());
}

fn valid_der() -> ([u8; 32], [u8; 32], Vec<u8>) {
    let r = [7u8; 32];
    let s = [9u8; 32];
    let mut out = vec![0u8; max_len(32)];
    let len = encode(&r, &s, &mut out);
    out.truncate(len);
    (r, s, out)
}

#[test]
fn decode_rejects_trailing_bytes() {
    let (_, _, mut der) = valid_der();
    der.push(0x00);
    let mut r_out = [0u8; 32];
    let mut s_out = [0u8; 32];
    assert!(decode(&der, &mut r_out, &mut s_out).is_none(), "must reject a trailing extra byte");
}

#[test]
fn decode_rejects_truncated_input() {
    let (_, _, der) = valid_der();
    let mut r_out = [0u8; 32];
    let mut s_out = [0u8; 32];
    for cut in 1..der.len() {
        assert!(
            decode(&der[..cut], &mut r_out, &mut s_out).is_none(),
            "must reject truncation to {cut} bytes"
        );
    }
}

