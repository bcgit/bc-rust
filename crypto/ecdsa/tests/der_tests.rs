//! Known-answer and malformed-input tests for [`bouncycastle_ecdsa::der`].
//!
//! The known-answer `der` bytes below were computed independently in Python (not from this crate),
//! reproducing ITU-T X.690 §8.3/§10.1's rules directly: strip redundant leading zero bytes from
//! each magnitude, prepend a `0x00` pad byte if the remaining leading byte's high bit is set, then
//! wrap both `INTEGER` TLVs in a `SEQUENCE` TLV, using the short-form length under 128 and the
//! one-octet long form (`0x81 <len>`) at or above it. `random.seed(20260915)`.

use bouncycastle_ecdsa::der::{decode, encode, max_len};

fn round_trip(r: &[u8], s: &[u8], expected_der: &[u8]) {
    let mut out = vec![0u8; max_len(r.len())];
    let len = encode(r, s, &mut out);
    assert_eq!(&out[..len], expected_der, "encode mismatch for r={r:x?} s={s:x?}");

    let mut r_out = vec![0u8; r.len()];
    let mut s_out = vec![0u8; s.len()];
    decode(&out[..len], &mut r_out, &mut s_out).expect("decode must accept its own encoding");
    assert_eq!(r_out, r, "decoded r mismatch");
    assert_eq!(s_out, s, "decoded s mismatch");
}

