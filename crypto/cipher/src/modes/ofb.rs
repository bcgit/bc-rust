/// The OFB mode type: the `M` of a mode-bound key such as `AES128Key<OFB>`, on the symmetric key
/// path with [`Ofb`] as its worker. Its key state is the keyed permutation alone.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OFB;

impl<P: Clone + ModeNames> Mode<P> for OFB {
    type KeyState = P;
    const KEY_TYPE: KeyType = KeyType::SymmetricCipherKey;
    const ALG_NAME: &'static str = P::OFB_ALG_NAME;

    fn key_state(perm: P) -> Self::KeyState {
        perm
    }
}

impl<P, const KEY_LEN: usize, const BLOCK_LEN: usize> SymmetricEncryptMode<P, KEY_LEN, BLOCK_LEN, 0>
    for OFB
where
    P: ElectronicCodeBook<KEY_LEN, BLOCK_LEN> + ModeNames + Clone,
{
    type Encryptor<'k>
        = Ofb<'k, P, Encrypting, BLOCK_LEN>
    where
        P: 'k;

    fn encrypt_init<'k>(
        state: &'k Self::KeyState,
        rng: &mut dyn RNG,
    ) -> Result<(Self::Encryptor<'k>, [u8; BLOCK_LEN]), SymmetricCipherError> {
        // `I1 = IV`. A decrypt-only permutation is refused by `StreamCipher::from_keystream`.
        let iv = random_iv::<BLOCK_LEN>(rng)?;
        Ok((StreamCipher::from_keystream(OfbKeyStream::from_perm(state, iv)), iv))
    }

    fn encrypt_init_nonce<'k>(
        state: &'k Self::KeyState,
        iv: &[u8; BLOCK_LEN],
    ) -> Self::Encryptor<'k> {
        StreamCipher::from_keystream(OfbKeyStream::from_perm(state, *iv))
    }
}

impl<P, const KEY_LEN: usize, const BLOCK_LEN: usize> SymmetricDecryptMode<P, KEY_LEN, BLOCK_LEN, 0>
    for OFB
where
    P: ElectronicCodeBook<KEY_LEN, BLOCK_LEN> + ModeNames + Clone,
{
    type Decryptor<'k>
        = Ofb<'k, P, Decrypting, BLOCK_LEN>
    where
        P: 'k;

    fn decrypt_init<'k>(
        state: &'k Self::KeyState,
        init_data: &[u8; BLOCK_LEN],
    ) -> Self::Decryptor<'k> {
        StreamCipher::from_keystream(OfbKeyStream::from_perm(state, *init_data))
    }
}

/// OFB mode over any [`ElectronicCodeBook`] permutation, with the direction encoded in the type:
/// the crate-private OFB keystream, `OfbKeyStream`, wrapped in a [`StreamCipher`]. `Dir` is
/// [`Encrypting`] or [`Decrypting`].
///
/// The initialization data is one block, the IV, so `INIT_DATA_LEN == BLOCK_LEN`.
pub type Ofb<'k, P, Dir, const BLOCK_LEN: usize> =
    StreamCipher<OfbKeyStream<'k, P, BLOCK_LEN>, Dir, BLOCK_LEN, BLOCK_LEN>;
