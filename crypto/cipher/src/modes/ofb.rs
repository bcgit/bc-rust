//! The Output Feedback mode of operation (NIST SP 800-38A §6.4), as a stream cipher.
//!
//! ```text
//! I1 = IV;
//! Ij = Oj-1               for j = 2 … n;
//! Oj = CIPH_K(Ij)         for j = 1, 2 … n;
//! Cj = Pj XOR Oj           for j = 1, 2 … n-1;
//! C*n = P*n XOR MSBu(On).
//! ```
//!
//! # A stream cipher, implemented over a block cipher
//!
//! The keystream is the IV iterated through the forward cipher and does not depend on the data,
//! so encryption and decryption are the same operation (decryption swaps `P` and `C`), and the
//! last block may be partial with the rest of `On` discarded, so there is no padding and no
//! ciphertext expansion.
//!
//! # Decryption uses the *forward* cipher function
//!
//! Both directions apply `CIPH_K`, so a permutation that implements only the forward direction
//! works here, and a permutation that decrypts only can still decrypt under OFB.
//!
//! # Strictly serial
//!
//! Sec 6.4: "In both OFB encryption and OFB decryption, each forward cipher function (except the
//! first) depends on the results of the previous forward cipher function; therefore, multiple
//! forward cipher functions cannot be performed in parallel." Both directions call
//! [`BlockPermutation::encrypt_block`] once per block, never the two- or four-block paths, so on
//! a permutation whose batch paths are faster, OFB runs at the single-block rate in both
//! directions, as CFB encryption does.
//!
//! # Usage Examples
//!
//! The direction is part of the type: [`Ofb<'k, P, Encrypting, ..>`](Ofb) implements
//! [`StreamCipherEncryptor`] and [`Ofb<'k, P, Decrypting, ..>`](Ofb) implements
//! [`StreamCipherDecryptor`]. The pair is reached through a mode-bound key, [`OFB`] on a key type
//! such as `bouncycastle_aes::AES128Key<OFB>`; over the toy permutation, through the mode traits:
//!
//! ```
//! # mod toy { include!("../../tests/common/toy_block_cipher.rs"); }
//! # use toy::ToyBlockCipher;
//! use bouncycastle_core::hazmat::{ElectronicCodeBook, KeyExpansion, Mode, SymmetricDecryptMode, SymmetricEncryptMode};
//! use bouncycastle_core::key_material::{KeyMaterial128, KeyType};
//! use bouncycastle_core::traits::{StreamCipherDecryptor, StreamCipherEncryptor};
//! use bouncycastle_cipher::modes::OFB;
//! use bouncycastle_rng::HashDRBG_SHA512;
//!
//! let key = KeyMaterial128::from_bytes_as_type(&[0x42; 16], KeyType::SymmetricCipherKey)
//!     .expect("a 16-byte symmetric cipher key");
//! let state = <OFB as Mode<ToyBlockCipher>>::key_state(ToyBlockCipher::new(&key).unwrap());
//!
//! let plaintext = b"the quick brown fox!!";
//! let mut data = *plaintext;
//!
//! let mut rng = HashDRBG_SHA512::new_from_os();
//! let (mut enc, iv) = OFB::encrypt_init(&state, &mut rng).expect("iv draw");
//! let bytes_written = enc.do_encrypt_inplace(&mut data).expect("encryption");
//! assert_eq!(bytes_written, plaintext.len());
//!
//! OFB::decrypt_init(&state, &iv).do_decrypt_inplace(&mut data).expect("decryption");
//! assert_eq!(data, *plaintext);
//! ```
//!
//! Other usage modes, such as streaming, behave the same as [`ctr`](crate::modes::ctr).
//!
//! # Memory Usage
//!
//! The state consists of a reference to the permutation, one block of `Oj-1`, the pending
//! keystream block held between calls and its byte count. After a call that ends inside a block
//! the two blocks hold the same `Oj`: the second is [`StreamCipher`]'s, which every keystream has.
//!
//! # 🚨 Security Considerations 🚨
//!
//! ## IV uniqueness
//!
//! Sec 5.3: "for the OFB mode, unique IVs must be used for each execution of the encryption
//! process". Appendix C:
//!
//! > "For the OFB mode, the IV need not be unpredictable, but it must be a nonce that is unique to
//! > each execution of the encryption operation."
//!
//! A repeated IV repeats the whole keystream: "if a plaintext block of any of these messages is
//! known, say, the jth plaintext block, then the jth output of the forward cipher function can be
//! determined easily from the jth ciphertext block of the message". The same holds if an input
//! block of one message is used as the IV of another, so, Appendix C again, "IVs for the OFB mode
//! should not be generated by invoking the block cipher on another IV".
//!
//! A key's `create_encryptor` draws a random block from the RNG, which meets this; its
//! `create_encryptor_nonce` hands the obligation to the caller.
//!
//! ## Malleability
//!
//! Appendix D: "for the OFB and CTR modes, the decryption of any ciphertext block is vulnerable
//! to the introduction of specific bit errors into that ciphertext block if its integrity is not
//! protected". Flipping a ciphertext bit flips the same plaintext bit and affects no other block,
//! so, unlike CFB, nothing downstream shows the change. OFB is not authenticated; prefer
//! [`gcm`](crate::modes::gcm).
//!
//! ## IV integrity
//!
//! Appendix D: "In the OFB mode, bit errors in the IV affect the decryption of every ciphertext
//! block". A tampered IV gives no controlled change, as it would under CBC, but loses the whole
//! message.

