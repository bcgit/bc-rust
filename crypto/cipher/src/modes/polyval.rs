    /// The reduction is taken exactly when the coefficient of `x^127` is set, which in GHASH's
    /// convention is the lowest bit of the last byte; every other bit only moves.
    #[test]
    fn mul_x_ghash_reduces_on_the_last_bit_alone() {
        let mut one_bit = [0u8; 16];
        one_bit[15] = 1;
        let mut r = [0u8; 16];
        r[0] = 0xE1;
        assert_eq!(mul_x_ghash_bytes(&one_bit), r);
        assert_eq!(mul_x_ghash_bytes(&[0xFF; 16]), {
            let mut e = [0xFF; 16];
            e[0] = 0x7F ^ 0xE1;
            e
        });
        assert_eq!(mul_x_ghash_bytes(&[0u8; 16]), [0u8; 16]);
        for bit in 0..128 {
            let mut v = [0u8; 16];
            v[bit / 8] = 0x80 >> (bit % 8);
            assert_eq!(mul_x_ghash_bytes(&v), mul_x_ghash_reference(&v), "bit {bit}");
            let mut w = [0xFFu8; 16];
            w[bit / 8] ^= 0x80 >> (bit % 8);
            assert_eq!(mul_x_ghash_bytes(&w), mul_x_ghash_reference(&w), "all but bit {bit}");
        }
        let mut rng = XorShift(0x6a09_e667_f3bc_c908);
        for _ in 0..256 {
            let v = rng.next_block();
            assert_eq!(mul_x_ghash_bytes(&v), mul_x_ghash_reference(&v));
        }
    }

