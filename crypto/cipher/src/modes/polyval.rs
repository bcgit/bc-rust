    /// `dot(a, b)` is POLYVAL of the one block `a` under `b`. The sum and the product are
    /// reached through `dot(c, 1) = c * x^-128`: it is linear, and it takes `a * b` to
    /// `dot(a, b)`.
    #[test]
    fn section_7_field_examples() {
        let (a, b) = (hex16(S7_A), hex16(S7_B));
        assert_eq!(polyval(&b, &[a]), hex16(S7_DOT_A_B));
        assert_eq!(polyval(&a, &[b]), hex16(S7_DOT_A_B));
        assert_eq!(polyval(&ONE, &[ONE]), hex16(S7_X_INV_128));
        assert_eq!(polyval(&ONE, &[hex16(S7_A_TIMES_B)]), hex16(S7_DOT_A_B));
        let sum = polyval(&ONE, &[hex16(S7_A_PLUS_B)]);
        let (da, db) = (polyval(&ONE, &[a]), polyval(&ONE, &[b]));
        assert_eq!(sum, core::array::from_fn(|i| da[i] ^ db[i]));
    }

