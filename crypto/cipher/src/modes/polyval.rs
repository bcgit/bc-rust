//! POLYVAL, the polynomial authenticator of AES-GCM-SIV (RFC 8452 Section 3).
//!
//! Computed with GHASH's multiplier rather than one of its own, through the relation the RFC
//! gives (Section 3, Appendix A):
//!
//! ```text
//! POLYVAL(H, X_1, ..., X_n) =
//! ByteReverse(GHASH(mulX_GHASH(ByteReverse(H)), ByteReverse(X_1), ..., ByteReverse(X_n)))
//! ```
//!
//! where GHASH is the bare iteration `Y_i = (Y_{i-1} + X_i) * H`, with no length block of its
//! own. `ByteReverse` costs nothing here: a field element is held as a [`Block`], whose two words
//! are the halves of the 16-byte string read big-endian, so the reversed string is loaded by
//! reading the two halves little-endian and swapping them, and stored the same way.

use crate::modes::gcm::ghash::{Block, mul};
use bouncycastle_utils::ct::Condition;
use bouncycastle_utils::secret::Secret;

/// `mulX_GHASH` (RFC 8452 Appendix A): multiplies `v` by `x` in GHASH's field, in place.
///
/// In GHASH's convention the leftmost bit of the string is the coefficient of `x^0`, so the
/// product is the string shifted right by one bit. The bit shifted out is the coefficient of
/// `x^127`; when it is set, `x^128` is reduced modulo GHASH's polynomial `x^128 + x^7 + x^2 + x
/// + 1` (Appendix A) by adding `x^7 + x^2 + x + 1`, the leading byte `0xE1`.
///
/// Constant time: the reduction is selected by a mask, with no branch on the bits of `v`.
fn mul_x_ghash(v: &mut Block) {
    let reduce = Condition::<u64>::from_lsb(v[1]);
    // The two shifted words share no bit, so `|` and `^` agree here: an equivalent mutant.
    v[1] = (v[1] >> 1) | (v[0] << 63);
    v[0] = (v[0] >> 1) ^ reduce.select(0xE1 << 56, 0);
}

/// The POLYVAL accumulator: `S_0 = 0; S_j = dot(S_{j-1} + X_j, H)` (RFC 8452 Section 3).
///
/// The key and the accumulator are derived from the AEAD key and the nonce, so both live in a
/// [`Secret`] and are zeroized on drop.
pub(super) struct Polyval {
    /// `mulX_GHASH(ByteReverse(H))`, the GHASH key of Appendix A's relation.
    h: Secret<Block>,
    /// `ByteReverse(S_j)`.
    s: Secret<Block>,
}

impl Polyval {
    /// `S_0 = 0`, keyed by the 16-byte field element `H`.
    pub(super) fn new(h: &[u8; 16]) -> Self {
        let mut hs: Secret<Block> = Secret::new();
        hs[0] = u64::from_le_bytes(h[8..].try_into().expect("second half of H is 8 bytes"));
        hs[1] = u64::from_le_bytes(h[..8].try_into().expect("first half of H is 8 bytes"));
        mul_x_ghash(&mut hs);
        Self { h: hs, s: Secret::new() }
    }

    /// `S_j = dot(S_{j-1} + X_j, H)` for one block `X_j`.
    pub(super) fn update_block(&mut self, block: &[u8; 16]) {
        self.s[0] ^=
            u64::from_le_bytes(block[8..].try_into().expect("second half of a block is 8 bytes"));
        self.s[1] ^=
            u64::from_le_bytes(block[..8].try_into().expect("first half of a block is 8 bytes"));
        *self.s = mul(&self.s, &self.h);
    }

    /// Absorbs `data` as blocks, the last one padded with zero bytes to a whole block, which is
    /// how RFC 8452 Section 4 feeds POLYVAL the additional data and the plaintext. Empty `data`
    /// absorbs nothing.
    ///
    /// Not a streaming update: every call ends on a block boundary. The bytes of a short last
    /// block are added to the accumulator where they fall, so no padded copy of them is made.
    pub(super) fn update_padded(&mut self, data: &[u8]) {
        let (blocks, rest) = data.as_chunks::<16>();
        for block in blocks {
            self.update_block(block);
        }
        if !rest.is_empty() {
            for (i, &byte) in rest.iter().enumerate() {
                self.s[1 - i / 8] ^= u64::from(byte) << (8 * (i % 8));
            }
            *self.s = mul(&self.s, &self.h);
        }
    }

    /// Writes `S_s`, the POLYVAL of the blocks absorbed so far, to `out`: a [`Secret`], since
    /// the tag is this value encrypted.
    pub(super) fn finish(&self, out: &mut Secret<[u8; 16]>) {
        out[..8].copy_from_slice(&self.s[1].to_le_bytes());
        out[8..].copy_from_slice(&self.s[0].to_le_bytes());
    }
}

