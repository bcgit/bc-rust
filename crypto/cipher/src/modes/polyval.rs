    /// Every Appendix C vector: POLYVAL of the printed input under the record authentication
    /// key, and the same from the vector's additional data and plaintext through the padding
    /// path, with the length block of Section 4 (two little-endian 64-bit bit lengths).
    #[test]
    fn appendix_c_polyval_inputs_and_results() {
        let mut counts = [0usize; 3];
        for (n, &(section, plaintext, aad, key, input, result)) in APPENDIX_C.iter().enumerate() {
            counts[["C.1", "C.2", "C.3"].iter().position(|s| *s == section).unwrap()] += 1;
            let (plaintext, aad, key) = (hex(plaintext), hex(aad), hex16(key));
            let (input, result) = (hex(input), hex16(result));
            assert_eq!(polyval(&key, &blocks_of(&input)), result, "vector {n}");

            let mut length_block = [0u8; 16];
            length_block[..8].copy_from_slice(&(aad.len() as u64 * 8).to_le_bytes());
            length_block[8..].copy_from_slice(&(plaintext.len() as u64 * 8).to_le_bytes());
            assert_eq!(length_block, input[input.len() - 16..], "vector {n}");
            let mut p = Polyval::new(&key);
            p.update_padded(&aad);
            p.update_padded(&plaintext);
            p.update_block(&length_block);
            assert_eq!(finished(&p), result, "vector {n}");
        }
        assert_eq!(counts, [24, 24, 2]);
    }

    // ---- The padding path, and the edges ----

    /// `update_padded` against zero-padding by hand and absorbing block by block, at every
    /// length from none to three blocks, on a non-zero accumulator.
    #[test]
    fn update_padded_is_update_block_over_the_zero_padded_data() {
        let mut rng = XorShift(0x1319_8a2e_0370_7344);
        for len in 0..=48 {
            let h = rng.next_block();
            let first = rng.next_block();
            // No zero bytes, so that a byte placed wrongly or dropped cannot go unnoticed.
            let data: Vec<u8> = rng.next_bytes(len).into_iter().map(|b| b | 1).collect();
            let mut padded = data.clone();
            padded.resize(len.div_ceil(16) * 16, 0);

            let mut by_block = Polyval::new(&h);
            by_block.update_block(&first);
            for block in blocks_of(&padded) {
                by_block.update_block(&block);
            }
            let mut by_padding = Polyval::new(&h);
            by_padding.update_block(&first);
            by_padding.update_padded(&data);
            assert_eq!(finished(&by_padding), finished(&by_block), "len {len}");

            let mut blocks = vec![first];
            blocks.extend(blocks_of(&padded));
            assert_eq!(finished(&by_padding), polyval_reference(&h, &blocks), "len {len}");
        }
    }

