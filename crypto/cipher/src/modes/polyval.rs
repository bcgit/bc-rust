    /// Keys at the edges of `mulX_GHASH`. `ByteReverse` puts the coefficient of `x^0` of `H`,
    /// the lowest bit of its first byte, where GHASH reads `x^127`, so that bit decides the
    /// reduction; the highest bit of the last byte is the one shifted across the two words.
    #[test]
    fn keys_with_the_end_bits_set_and_clear() {
        let x = [hex16(A_X1), hex16(A_X2)];
        let base = hex16(A_H);
        for first_low in [false, true] {
            for last_high in [false, true] {
                for middle in [false, true] {
                    let mut h = base;
                    h[0] = (h[0] & 0xFE) | u8::from(first_low);
                    h[15] = (h[15] & 0x7F) | (u8::from(last_high) << 7);
                    // Byte 8's lowest bit is the bit carried from one word to the other.
                    h[8] = (h[8] & 0xFE) | u8::from(middle);
                    assert_eq!(polyval(&h, &x), polyval_reference(&h, &x), "H = {h:02x?}");
                    assert_eq!(polyval(&h, &x), polyval_through_ghash(&h, &x), "H = {h:02x?}");
                }
            }
        }
        for bit in 0..128 {
            let mut h = [0u8; 16];
            h[bit / 8] = 1 << (bit % 8);
            assert_eq!(polyval(&h, &x), polyval_reference(&h, &x), "H = x^{bit}");
        }
    }

    #[test]
    fn all_ones() {
        let ones = [0xFFu8; 16];
        assert_eq!(polyval(&ones, &[ones]), dot_reference(&ones, &ones));
        assert_eq!(polyval(&ones, &[ones, ones]), polyval_reference(&ones, &[ones, ones]));
        assert_eq!(polyval(&ones, &[ones, ones]), polyval_through_ghash(&ones, &[ones, ones]));
        let mut p = Polyval::new(&ones);
        p.update_padded(&[0xFF; 31]);
        let mut short = ones;
        short[15] = 0;
        assert_eq!(finished(&p), polyval_reference(&ones, &[ones, short]));
    }

