//! Type aliases for ARIA (RFC 5794, KS X 1213-1) in CFB mode (NIST SP 800-38A Sec 6.3).
//!
//! `bouncycastle-modes` is deliberately cipher-agnostic, so `Cfb` takes the permutation, the
//! direction, and the `KEY_LEN` / `BLOCK_LEN` const parameters. These aliases pin the ARIA values
//! so callers never spell them out. They add nothing to the engine: the permutation still
//! implements none of the data-encryption traits itself (see the crate docs), the mode does.
//!
//! The segment size is the full block, so these are **CFB128**. SP 800-38A's `s = 8` variant is a
//! different, non-interoperable mode with its own aliases -- [`ARIA_CFB8_128`](crate::ARIA_CFB8_128)
//! and friends -- and `s = 1` is not implemented; see the `bouncycastle_modes::Cfb` docs.

use crate::{ARIA_128, ARIA_192, ARIA_256, BLOCK_LEN};
use bouncycastle_modes::Cfb;

/// ARIA-128 in CFB128 mode. `Dir` is [`bouncycastle_modes::Encrypting`] or
/// [`bouncycastle_modes::Decrypting`]; the wrong direction is a compile error, not a runtime check.
///
/// CFB is a stream cipher, so the data is a `&mut [u8]` of any length and the ciphertext is exactly
/// as long as the plaintext. The IV is generated by encryption and returned; it is never supplied.
/// Encryption and decryption work in place.
///
/// ```
/// use bouncycastle_aria::ARIA_CFB_128;
/// use bouncycastle_core::key_material::{KeyMaterial, KeyType};
/// use bouncycastle_core::traits::{StreamCipherDecryptor, StreamCipherEncryptor};
/// use bouncycastle_modes::{Decrypting, Encrypting};
///
/// let key = KeyMaterial::<16>::from_bytes_as_type(&[0x42; 16], KeyType::SymmetricCipherKey)
///     .expect("a 16-byte symmetric cipher key");
/// // 47 bytes: a stream cipher does not need a whole number of blocks.
/// let message = [0u8; 47];
/// let mut data = message;
/// let (_, iv) = ARIA_CFB_128::<Encrypting>::encrypt(&key, &mut data).unwrap();
/// assert_ne!(data, message);
/// ARIA_CFB_128::<Decrypting>::decrypt(&key, &iv, &mut data).unwrap();
/// assert_eq!(data, message);
///
/// // Streaming, at any byte boundary:
/// let (mut enc, iv) = ARIA_CFB_128::<Encrypting>::do_encrypt_init(&key).unwrap();
/// let mut first = [0u8; 5];
/// let mut rest = [1u8; 30];
/// enc.do_encrypt(&mut first).unwrap();
/// enc.do_encrypt(&mut rest).unwrap();
/// let mut dec = ARIA_CFB_128::<Decrypting>::do_decrypt_init(&key, &iv).unwrap();
/// dec.do_decrypt(&mut first).unwrap();
/// dec.do_decrypt(&mut rest).unwrap();
/// assert_eq!(first, [0u8; 5]);
/// assert_eq!(rest, [1u8; 30]);
/// ```
#[allow(non_camel_case_types)]
pub type ARIA_CFB_128<Dir> = Cfb<ARIA_128, Dir, 16, BLOCK_LEN>;

