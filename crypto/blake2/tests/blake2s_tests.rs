    fn h(s: &str) -> Vec<u8> {
        hex::decode(s).unwrap()
    }

    /// The KAT message of length `len`: bytes 0, 1, ..., len - 1.
    fn msg(len: usize) -> &'static [u8] {
        &DUMMY_SEED[..len]
    }

    /// The KAT key material, bytes 0..KK_MAX, as a MAC key.
    fn kat_material() -> KeyMaterial<KK_MAX> {
        KeyMaterial::<KK_MAX>::from_bytes_as_type(&DUMMY_SEED[..KK_MAX], KeyType::MACKey).unwrap()
    }

    /// The KAT key object.
    fn kat_key() -> K {
        K::from_key_material(&kat_material()).unwrap()
    }

    /// A MAC key of `len` bytes 0xA5.., tagged with `strength`.
    fn key_with(len: usize, strength: SecurityStrength) -> KeyMaterial<256> {
        let mut key =
            KeyMaterial::<256>::from_bytes_as_type(&[0xA5u8; 256][..len], KeyType::MACKey).unwrap();
        do_hazardous_operations(&mut key, |k| k.set_security_strength(strength)).unwrap();
        key
    }

    fn kat(len: usize) -> (Vec<u8>, Vec<u8>) {
        let (_, unkeyed, keyed) = KAT.iter().find(|(n, _, _)| *n == len).unwrap();
        (h(unkeyed), h(keyed))
    }

