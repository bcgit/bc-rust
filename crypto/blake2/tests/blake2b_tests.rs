    /// Every embedded KAT entry, one-shot and streamed byte-at-a-time, hash and MAC.
    #[test]
    fn official_kat() {
        for (len, unkeyed, keyed) in KAT {
            let (unkeyed, keyed) = (h(unkeyed), h(keyed));
            let m = msg(len);

            assert_eq!(H::new().hash(m), unkeyed, "hash, len {len}");
            let mut hash = H::new();
            for byte in m {
                hash.do_update(core::slice::from_ref(byte));
            }
            assert_eq!(hash.do_final(), unkeyed, "byte-at-a-time hash, len {len}");

            assert_eq!(kat_key().create_generator().mac(m), keyed, "mac, len {len}");
            let mut mac = kat_key().create_generator();
            for byte in m {
                mac.do_update(core::slice::from_ref(byte));
            }
            assert_eq!(mac.do_final(), keyed, "byte-at-a-time mac, len {len}");
        }
    }

    /// Splitting the input at every point, and feeding it in every chunk size up to two blocks,
    /// gives the one-shot answer. This walks every branch of the buffering in do_update.
    #[test]
    fn streaming_splits() {
        let (unkeyed, keyed) = kat(255);
        let m = msg(255);
        for split in 0..=m.len() {
            let mut hash = H::new();
            hash.do_update(&m[..split]);
            hash.do_update(&[]);
            hash.do_update(&m[split..]);
            assert_eq!(hash.do_final(), unkeyed, "split at {split}");

            let mut mac = kat_key().create_generator();
            mac.do_update(&m[..split]);
            mac.do_update(&m[split..]);
            assert_eq!(mac.do_final(), keyed, "keyed split at {split}");
        }
        for chunk in 1..=(2 * BB + 1) {
            let mut hash = H::new();
            let mut mac = kat_key().create_generator();
            for part in m.chunks(chunk) {
                hash.do_update(part);
                mac.do_update(part);
            }
            assert_eq!(hash.do_final(), unkeyed, "chunk size {chunk}");
            assert_eq!(mac.do_final(), keyed, "keyed chunk size {chunk}");
        }
    }

