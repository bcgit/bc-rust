    /// Pins the documented state layout.
    #[test]
    fn suspend_layout() {
        let mut hash = H::new();
        hash.do_update(b"abc");
        let state = hash.suspend();
        // h[0] = IV[0] ^ 0x01010000 ^ (kk << 8) ^ nn, little-endian: RFC 7693 Appendix A shows
        // v[0] = 6A09E667F2BDC948 at i = 0.
        assert_eq!(state[3..11], 0x6A09E667F2BDC948u64.to_le_bytes());
        assert!(state[T_OFF..BUF_OFF].iter().all(|&b| b == 0), "t = 0");
        assert_eq!(&state[BUF_OFF..BUF_OFF + 3], b"abc");
        assert_eq!(state[BUF_LEN_OFF], 3);

        let mut hash = H::new();
        hash.do_update(msg(BB + 1));
        let state = hash.suspend();
        assert_eq!(state[T_OFF], BB as u8, "t = bb after one block");
        assert_eq!(state[BUF_OFF], BB as u8, "buf holds message byte bb");
        assert_eq!(state[BUF_LEN_OFF], 1);
    }

    #[test]
    fn suspend_rejects_bad_buf_len() {
        let mut hash = H::new();
        hash.do_update(msg(BB));
        let mut state = hash.suspend();
        // A full buffer is valid ...
        assert_eq!(state[BUF_LEN_OFF], BB as u8);
        let (expected, _) = kat(BB);
        assert_eq!(H::from_suspended(state).unwrap().do_final(), expected);
        // ... one more byte is not.
        state[BUF_LEN_OFF] = BB as u8 + 1;
        assert!(matches!(H::from_suspended(state), Err(SuspendableError::InvalidData)));
        state[BUF_LEN_OFF] = 0xFF;
        assert!(matches!(H::from_suspended(state), Err(SuspendableError::InvalidData)));
    }

    /// Before any compression the hash's h must be the unkeyed initial state: a keyed state
    /// (h carries kk in p[0]) or a tampered h is rejected.
    #[test]
    fn suspend_hash_rejects_foreign_h() {
        // A fresh MAC state has the same shape as a hash state with a full buffer.
        let mac_state: [u8; STATE_LEN] = kat_key().create_generator().suspend();
        assert!(matches!(H::from_suspended(mac_state), Err(SuspendableError::InvalidData)));

        let mut hash = H::new();
        hash.do_update(b"abc");
        let state = hash.suspend();
        assert!(H::from_suspended(state).is_ok());
        for i in [3, 4, (3 + T_OFF) / 2, T_OFF - 1] {
            let mut st = state;
            st[i] ^= 0x01;
            assert!(
                matches!(H::from_suspended(st), Err(SuspendableError::InvalidData)),
                "h byte {i}"
            );
        }

        // After a compression h is no longer the initial state, and that is fine.
        let mut hash = H::new();
        hash.do_update(msg(BB + 1));
        assert!(H::from_suspended(hash.suspend()).is_ok());
    }

    /// t must be a whole number of blocks, in both the hash and the MAC state.
    #[test]
    fn suspend_rejects_bad_t() {
        let mut hash = H::new();
        hash.do_update(msg(BB + 1));
        let state = hash.suspend();
        assert_eq!(state[T_OFF], BB as u8);
        for bad in [1u8, BB as u8 - 1, BB as u8 + 1] {
            let mut st = state;
            st[T_OFF] = bad;
            assert!(matches!(H::from_suspended(st), Err(SuspendableError::InvalidData)), "t {bad}");
        }
        // A larger multiple of bb is fine.
        let mut st = state;
        st[T_OFF + 1] = 1;
        assert!(H::from_suspended(st).is_ok());

        let key = kat_key();
        let mut mac = key.create_generator();
        mac.do_update(b"x");
        let state = mac.suspend();
        assert_eq!(state[T_OFF], BB as u8);
        for bad in [1u8, BB as u8 - 1, BB as u8 + 1] {
            let mut st = state;
            st[T_OFF] = bad;
            assert!(matches!(M::from_suspended(st, &key), Err(SuspendableError::InvalidData)));
        }
    }

