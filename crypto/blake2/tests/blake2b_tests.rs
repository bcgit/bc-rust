    /// BLAKE2 is byte-oriented: 0 partial bits is do_final, 1..=7 is InvalidInput, more is
    /// InvalidLength.
    #[test]
    fn partial_bits() {
        let (expected, _) = kat(3);
        let started = || {
            let mut hash = H::new();
            hash.do_update(msg(3));
            hash
        };

        assert_eq!(started().do_final_partial_bits(0xFF, 0).unwrap(), expected);
        let mut out = [0xAAu8; NN + 1];
        assert_eq!(started().do_final_partial_bits_out(0xFF, 0, &mut out).unwrap(), NN);
        assert_eq!(&out[..NN], expected.as_slice());
        assert_eq!(out[NN], 0);

        for num_bits in 1..=7 {
            assert!(matches!(
                started().do_final_partial_bits(0x80, num_bits),
                Err(HashError::InvalidInput(_))
            ));
            out.fill(0xAA);
            assert!(matches!(
                started().do_final_partial_bits_out(0x80, num_bits, &mut out),
                Err(HashError::InvalidInput(_))
            ));
            assert!(out.iter().all(|&b| b == 0), "the buffer is zeroed before the error");
        }
        for num_bits in [8, 9, 15, 16, 64, usize::MAX] {
            assert!(matches!(
                started().do_final_partial_bits(0x80, num_bits),
                Err(HashError::InvalidLength(_))
            ));
            out.fill(0xAA);
            assert!(matches!(
                started().do_final_partial_bits_out(0x80, num_bits, &mut out),
                Err(HashError::InvalidLength(_))
            ));
            assert!(out.iter().all(|&b| b == 0), "the buffer is zeroed before the error");
        }
    }

    /// The BLAKE2-specific construction rules; type and strength policy is the framework's.
    #[test]
    fn key_validation() {
        // Empty key: kk = 0 is the unkeyed hash, not a MAC.
        let empty = KeyMaterial::<KK_MAX>::new();
        assert!(matches!(K::from_key_material_allow_weak(&empty), Err(MACError::InvalidLength(_))));

        // Over-long key.
        let long = key_with(KK_MAX + 1, SecurityStrength::_256bit);
        assert!(matches!(K::from_key_material(&long), Err(MACError::InvalidLength(_))));
        assert!(matches!(K::from_key_material_allow_weak(&long), Err(MACError::InvalidLength(_))));

        // Boundary lengths are accepted.
        assert!(K::from_key_material_allow_weak(&key_with(1, SecurityStrength::None)).is_ok());
        assert!(K::from_key_material(&key_with(KK_MAX, SecurityStrength::_256bit)).is_ok());

        // Order: type before strength before length.
        let mut wrong = key_with(KK_MAX + 1, SecurityStrength::None);
        do_hazardous_operations(&mut wrong, |k| k.set_key_type(KeyType::SymmetricCipherKey))
            .unwrap();
        assert!(matches!(
            K::from_key_material(&wrong),
            Err(MACError::KeyMaterialError(KeyMaterialError::InvalidKeyType(_)))
        ));
        let none64 = key_with(64, SecurityStrength::None);
        assert!(matches!(
            K::from_key_material(&none64),
            Err(MACError::KeyMaterialError(KeyMaterialError::SecurityStrength(_)))
        ));
        let weak = key_with(KK_MAX, SecurityStrength::_192bit);
        assert!(matches!(
            K::from_key_material(&weak),
            Err(MACError::KeyMaterialError(KeyMaterialError::SecurityStrength(_)))
        ));

        // An all-zero key is tagged Zeroized (no strength): allowed only as a weak key, and it is
        // a real key, distinct from the unkeyed hash.
        let zero =
            KeyMaterial::<KK_MAX>::from_bytes_as_type(&[0u8; KK_MAX], KeyType::MACKey).unwrap();
        assert_eq!(zero.key_type(), KeyType::Zeroized);
        assert!(matches!(
            K::from_key_material(&zero),
            Err(MACError::KeyMaterialError(KeyMaterialError::SecurityStrength(_)))
        ));
        let tag = K::from_key_material_allow_weak(&zero).unwrap().mac(b"abc");
        assert_ne!(tag, H::new().hash(b"abc"));
    }

    /// generate draws KK_MAX bytes from the RNG and refuses an RNG below the MAC's strength.
    #[test]
    fn key_generate() {
        let seed: [u8; 64] = core::array::from_fn(|i| DUMMY_SEED[300 + i]);
        let generated = K::generate(&mut FixedSeedRNG::<64>::new(seed)).unwrap();
        let material =
            KeyMaterial::<KK_MAX>::from_bytes_as_type(&seed[..KK_MAX], KeyType::MACKey).unwrap();
        assert_eq!(generated.mac(b"abc"), K::from_key_material(&material).unwrap().mac(b"abc"));

        let mut weak_rng = FixedSeedRNG::<64>::new(seed);
        weak_rng.set_security_strength(SecurityStrength::_192bit);
        assert!(matches!(
            K::generate(&mut weak_rng),
            Err(MACError::KeyMaterialError(KeyMaterialError::SecurityStrength(_)))
        ));
    }

    /// The key length kk is bound into the parameter block: a key and the same key with a zero
    /// byte appended give different tags, even though they pad to the same block d[0].
    #[test]
    fn key_length_bound() {
        let short = key_with(KK_MAX - 1, SecurityStrength::_256bit);
        let mut padded_bytes = [0xA5u8; KK_MAX];
        padded_bytes[KK_MAX - 1] = 0;
        let padded =
            KeyMaterial::<KK_MAX>::from_bytes_as_type(&padded_bytes, KeyType::MACKey).unwrap();
        assert_ne!(
            K::from_key_material_allow_weak(&short).unwrap().create_generator().mac(b"abc"),
            K::from_key_material_allow_weak(&padded).unwrap().create_generator().mac(b"abc")
        );
    }

